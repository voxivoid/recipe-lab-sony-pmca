/*
 * The bodies rlisp knows: where av-cam keeps the two ISP setters it patches, per model and firmware.
 *
 * Rows come from a6000-qemu's tools/port/port_scan.py run on the av-cam.bin of Sony's updater for that firmware.
 * av-cam is position independent and its load address is in the camera's own Backup.bin, so a row holds offsets into
 * the image and the 32 bytes found there. `base` is the load PA, or a first guess (the A6000's 0x83541000; the a6300's
 * updater loads av-cam at the same VA): when both signatures do not match there, rlisp looks for the one page-aligned
 * base where they do, and `rlisp probe` reports it. 0 means no guess.
 *
 * `enabled` 0 means probe only: apply answers "REFUSE untested". A row is enabled once a camera's probe matched it.
 * IspBodies.java mirrors model, fw and enabled; IspBodiesTest fails when the two disagree.
 */
#define SIG 32

struct body {
    const char *model, *fw;
    ul off[2];                 /* image offset of the gamma leaf and the matrix setter */
    u8 sig[2][SIG];            /* their first 32 bytes in the updater's av-cam.bin */
    ul base;                   /* av-cam load PA, 0 when unknown */
    ul gamma_pa, matrix_pa;
    int enabled;
};

